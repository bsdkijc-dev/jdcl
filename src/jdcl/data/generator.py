"""Deterministic synthetic data generator for JFLM 2027.

SYNTHETIC DATA DISCLAIMER:
All records generated by this module are 100% synthetic modeling assumptions.
No real citizen identities, litigant records, or judicial case files are used.
"""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, Tuple

import numpy as np
import pandas as pd

from jdcl.config import PROJECT_ROOT
from jdcl.data.manifest import compute_sha256, write_manifest


DATASET_VERSION = "1.0.0-synthetic"
DATA_ORIGIN_TAG = "SYNTHETIC_JFLM_2027_V1"

PROVINCE_GROUPS = [
    "Jawa Barat",
    "Jawa Tengah",
    "Jawa Timur",
    "Nusa Tenggara Barat",
    "Nusa Tenggara Timur",
    "Sumatera Utara",
    "Sulawesi Selatan",
    "Kalimantan Tengah",
    "Maluku",
    "Papua",
]
PROVINCE_WEIGHTS = [0.16, 0.14, 0.15, 0.08, 0.08, 0.11, 0.10, 0.07, 0.06, 0.05]

REGION_TIERS = ["Urban", "Peri-Urban", "Rural", "Remote-3T"]
COURT_JURISDICTIONS = ["General_District", "Religious_Family", "Administrative", "Industrial_Labor"]
SERVICE_CHANNELS = ["Posbakum_InPerson", "Mobile_Circuit_Court", "eCourt_Digital", "Community_Paralegal"]
DISPUTE_CATEGORIES = [
    "Civil_Small_Claims",
    "Family_Custody_Support",
    "Land_Agrarian",
    "Labor_Dispute",
    "Legal_Aid_Consultation",
]
VULNERABILITY_GROUPS = [
    "Standard",
    "Low_Income_Prodeo",
    "Indigenous_Remote",
    "Person_With_Disability",
    "Female_Headed_Household",
]
GENDER_CATEGORIES = ["Female", "Male", "Undisclosed"]


def generate_jflm_2027_dataframe(n_rows: int = 10000, seed: int = 20270101) -> pd.DataFrame:
    """Generate deterministic synthetic last-mile justice delivery records."""
    if n_rows <= 0:
        raise ValueError("n_rows must be positive")

    rng = np.random.default_rng(seed)
    record_id = [f"JFLM2027-{i + 1:06d}" for i in range(n_rows)]

    province_group = rng.choice(PROVINCE_GROUPS, size=n_rows, p=PROVINCE_WEIGHTS)

    # Region tier conditional on eastern/archipelagic vs Java provinces (synthetic assumption)
    remote_provinces = {"Nusa Tenggara Timur", "Maluku", "Papua", "Kalimantan Tengah"}
    region_tier = np.empty(n_rows, dtype=object)
    for i, prov in enumerate(province_group):
        if prov in remote_provinces:
            region_tier[i] = rng.choice(REGION_TIERS, p=[0.18, 0.22, 0.34, 0.26])
        else:
            region_tier[i] = rng.choice(REGION_TIERS, p=[0.36, 0.30, 0.26, 0.08])

    court_jurisdiction = rng.choice(COURT_JURISDICTIONS, size=n_rows, p=[0.42, 0.36, 0.12, 0.10])
    dispute_category = rng.choice(DISPUTE_CATEGORIES, size=n_rows, p=[0.26, 0.30, 0.16, 0.10, 0.18])
    gender_category = rng.choice(GENDER_CATEGORIES, size=n_rows, p=[0.48, 0.46, 0.06])
    vulnerability_group = rng.choice(VULNERABILITY_GROUPS, size=n_rows, p=[0.45, 0.28, 0.08, 0.07, 0.12])

    # Distance and digital connectivity driven by region tier
    distance_to_court_km = np.zeros(n_rows, dtype=float)
    digital_connectivity_index = np.zeros(n_rows, dtype=float)
    service_channel = np.empty(n_rows, dtype=object)

    tier_dist_params = {
        "Urban": (1.5, 12.0, 0.82, 0.10, [0.35, 0.05, 0.50, 0.10]),
        "Peri-Urban": (8.0, 32.0, 0.66, 0.14, [0.34, 0.14, 0.32, 0.20]),
        "Rural": (22.0, 85.0, 0.44, 0.16, [0.22, 0.34, 0.14, 0.30]),
        "Remote-3T": (55.0, 260.0, 0.24, 0.14, [0.10, 0.48, 0.07, 0.35]),
    }

    for i, tier in enumerate(region_tier):
        d_low, d_high, c_mean, c_std, ch_probs = tier_dist_params[tier]
        distance_to_court_km[i] = np.round(rng.uniform(d_low, d_high), 2)
        digital_connectivity_index[i] = np.round(np.clip(rng.normal(c_mean, c_std), 0.02, 0.99), 3)
        service_channel[i] = rng.choice(SERVICE_CHANNELS, p=ch_probs)

    distance_to_court_km = np.clip(distance_to_court_km, 0.5, 350.0)

    # Travel cost (IDR thousands, pure numeric, no currency symbol)
    travel_cost_idr_thousands = np.round(
        np.clip(12.0 + 4.8 * distance_to_court_km + rng.normal(0.0, 22.0, size=n_rows), 5.0, 2500.0),
        2,
    )

    legal_aid_available = rng.binomial(1, np.where(np.isin(region_tier, ["Urban", "Peri-Urban"]), 0.72, 0.46))
    fee_waiver_prodeo = rng.binomial(
        1,
        np.where(np.isin(vulnerability_group, ["Low_Income_Prodeo", "Female_Headed_Household", "Person_With_Disability"]), 0.68, 0.18),
    )

    case_complexity_index = np.round(np.clip(rng.normal(4.8, 1.9, size=n_rows), 1.0, 10.0), 2)

    # Optional fields with realistic synthetic missingness (~2%, never zero-imputed)
    digital_intake_score = np.round(
        np.clip(100.0 * digital_connectivity_index + rng.normal(0.0, 8.0, size=n_rows), 0.0, 100.0),
        2,
    ).astype(float)
    mask_intake = rng.random(n_rows) < 0.022
    digital_intake_score[mask_intake] = np.nan

    paralegal_hours = np.round(
        np.clip(2.5 + 1.8 * case_complexity_index + 3.0 * legal_aid_available + rng.normal(0.0, 2.5, size=n_rows), 0.0, 80.0),
        2,
    ).astype(float)
    mask_paralegal = rng.random(n_rows) < 0.018
    paralegal_hours[mask_paralegal] = np.nan

    # Structural synthetic equation for resolution_days
    channel_effect = np.select(
        [
            service_channel == "eCourt_Digital",
            service_channel == "Mobile_Circuit_Court",
            service_channel == "Community_Paralegal",
            service_channel == "Posbakum_InPerson",
        ],
        [-12.0, -6.5, -4.0, 0.0],
        default=0.0,
    )
    vuln_penalty = np.where(vulnerability_group == "Standard", 0.0, 6.5)
    raw_days = (
        24.0
        + 0.28 * distance_to_court_km
        + 6.2 * case_complexity_index
        - 16.0 * digital_connectivity_index
        - 9.5 * legal_aid_available
        - 4.5 * fee_waiver_prodeo
        + channel_effect
        + vuln_penalty
        + rng.normal(0.0, 9.0, size=n_rows)
    )
    resolution_days = np.round(np.clip(raw_days, 1.0, 365.0), 1)

    # SLA completion within 90 days with slight probabilistic dropout on high cost/distance
    sla_logit = 2.4 - 0.032 * (resolution_days - 60.0) - 0.0012 * travel_cost_idr_thousands + 0.45 * legal_aid_available
    sla_prob = 1.0 / (1.0 + np.exp(-np.clip(sla_logit, -20.0, 20.0)))
    service_completed = rng.binomial(1, sla_prob).astype(int)

    df = pd.DataFrame(
        {
            "record_id": record_id,
            "province_group": province_group,
            "region_tier": region_tier,
            "court_jurisdiction": court_jurisdiction,
            "service_channel": service_channel,
            "dispute_category": dispute_category,
            "vulnerability_group": vulnerability_group,
            "gender_category": gender_category,
            "distance_to_court_km": distance_to_court_km,
            "travel_cost_idr_thousands": travel_cost_idr_thousands,
            "digital_connectivity_index": digital_connectivity_index,
            "legal_aid_available": legal_aid_available,
            "fee_waiver_prodeo": fee_waiver_prodeo,
            "digital_intake_score": digital_intake_score,
            "paralegal_hours": paralegal_hours,
            "case_complexity_index": case_complexity_index,
            "resolution_days": resolution_days,
            "service_completed": service_completed,
            "data_origin": DATA_ORIGIN_TAG,
        }
    )
    return df


def build_manifest(
    df: pd.DataFrame,
    csv_path: Path,
    seed: int,
) -> Dict[str, Any]:
    sha256 = compute_sha256(csv_path)
    return {
        "dataset_id": "jflm_2027_synthetic_v1",
        "dataset_version": DATASET_VERSION,
        "initiative": "Justice for the Last Mile Challenge 2027 (JFLM 2027)",
        "data_classification": "P1_SYNTHETIC_PUBLIC_CANDIDATE",
        "is_synthetic": True,
        "disclaimer": (
            "100% synthetic dataset generated deterministically for research and competition "
            "infrastructure. Contains NO real citizen identities, litigant records, or judicial cases."
        ),
        "generator": {
            "module": "jdcl.data.generator",
            "random_seed": int(seed),
            "row_count": int(len(df)),
            "column_count": int(len(df.columns)),
        },
        "provenance": {
            "created_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
            "file_path": str(csv_path.relative_to(PROJECT_ROOT)) if csv_path.is_relative_to(PROJECT_ROOT) else str(csv_path),
            "sha256": sha256,
            "licence": "CC0-1.0 / Apache-2.0 (Synthetic Code & Output)",
            "pii_present": False,
            "human_publication_approval": False,
        },
        "columns": list(df.columns),
    }


def generate_and_save(
    n_rows: int = 10000,
    seed: int = 20270101,
    csv_path: Path | None = None,
    manifest_path: Path | None = None,
) -> Tuple[pd.DataFrame, Dict[str, Any]]:
    target_csv = csv_path or (PROJECT_ROOT / "data" / "synthetic" / "jflm_2027.csv")
    target_manifest = manifest_path or (PROJECT_ROOT / "data" / "manifests" / "jflm_2027.yml")

    target_csv.parent.mkdir(parents=True, exist_ok=True)
    df = generate_jflm_2027_dataframe(n_rows=n_rows, seed=seed)
    df.to_csv(target_csv, index=False, encoding="utf-8")

    manifest = build_manifest(df, target_csv, seed=seed)
    write_manifest(manifest, target_manifest)
    return df, manifest


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate deterministic JFLM 2027 synthetic dataset.")
    parser.add_argument("--rows", type=int, default=10000)
    parser.add_argument("--seed", type=int, default=20270101)
    parser.add_argument("--output", type=Path, default=None)
    parser.add_argument("--manifest", type=Path, default=None)
    args = parser.parse_args()

    df, manifest = generate_and_save(
        n_rows=args.rows,
        seed=args.seed,
        csv_path=args.output,
        manifest_path=args.manifest,
    )
    print(f"Generated {len(df)} synthetic rows -> sha256={manifest['provenance']['sha256'][:12]}...")


if __name__ == "__main__":
    main()
